import { describe, expect, it } from 'vitest';
import { generateInsights, parseInsightOutput } from '../src/lib/ai';
import { buildFallbackInsights, findUngroundedNumbers } from '../src/lib/insights';
import { sampleSummary, validAiOutput } from './helpers';

describe('parseInsightOutput', () => {
  it('accepts a valid object and sorts action items by priority', () => {
    const shuffled = { ...validAiOutput, action_items: [...validAiOutput.action_items].reverse() };
    const r = parseInsightOutput(shuffled, { requireHinglish: true });
    expect(r.ok).toBe(true);
    if (r.ok) expect(r.data.action_items.map((a) => a.priority)).toEqual([1, 2, 3, 4, 5]);
  });

  it('extracts JSON wrapped in extra text (common LLM habit)', () => {
    const r = parseInsightOutput('Sure! Here it is:\n```json\n' + JSON.stringify(validAiOutput) + '\n```');
    expect(r.ok).toBe(true);
  });

  it('rejects anything other than exactly 5 action items', () => {
    const four = { ...validAiOutput, action_items: validAiOutput.action_items.slice(0, 4) };
    const r = parseInsightOutput(four);
    expect(r.ok).toBe(false);
    if (!r.ok) expect(r.error).toMatch(/exactly 5/);
  });

  it('rejects duplicate priorities', () => {
    const dup = { ...validAiOutput, action_items: validAiOutput.action_items.map((a) => ({ ...a, priority: 1 })) };
    expect(parseInsightOutput(dup).ok).toBe(false);
  });

  it('requires description and supporting_metrics on every item', () => {
    const noDesc = {
      ...validAiOutput,
      action_items: validAiOutput.action_items.map(({ description: _d, ...rest }) => rest),
    };
    expect(parseInsightOutput(noDesc).ok).toBe(false);
    const noMetrics = {
      ...validAiOutput,
      action_items: validAiOutput.action_items.map((a) => ({ ...a, supporting_metrics: [] })),
    };
    expect(parseInsightOutput(noMetrics).ok).toBe(false);
  });

  it('rejects non-JSON and missing Hinglish when required', () => {
    expect(parseInsightOutput('I cannot help with that').ok).toBe(false);
    expect(parseInsightOutput('{not json}').ok).toBe(false);
    const { summary_hinglish: _h, ...noHinglish } = validAiOutput;
    expect(parseInsightOutput(noHinglish, { requireHinglish: true }).ok).toBe(false);
    expect(parseInsightOutput(noHinglish, { requireHinglish: false }).ok).toBe(true);
  });

  it('rejects outputs that guarantee results', () => {
    const promise = {
      ...validAiOutput,
      action_items: validAiOutput.action_items.map((a, i) =>
        i === 0 ? { ...a, expected_impact: 'Guaranteed #1 ranking in 2 weeks' } : a,
      ),
    };
    const r = parseInsightOutput(promise);
    expect(r.ok).toBe(false);
    if (!r.ok) expect(r.error).toMatch(/guarantee/i);
  });

  it('rejects supporting metrics with numbers that are not in the data (fabricated)', () => {
    const s = sampleSummary();
    const invented = {
      ...validAiOutput,
      action_items: validAiOutput.action_items.map((a, i) =>
        i === 0 ? { ...a, supporting_metrics: ['Clicks: 98,765'] } : a,
      ),
    };
    const r = parseInsightOutput(invented, { source: s });
    expect(r.ok).toBe(false);
    if (!r.ok) expect(r.error).toMatch(/98765/);

    const grounded = {
      ...validAiOutput,
      action_items: validAiOutput.action_items.map((a, i) =>
        i === 0 ? { ...a, supporting_metrics: ['Clicks: 1,240 (-17.3%)', 'Lab LCP: 6.2 s', '"teeth whitening pune": position 11.4'] } : a,
      ),
    };
    expect(parseInsightOutput(grounded, { source: s }).ok).toBe(true);
  });
});

describe('findUngroundedNumbers', () => {
  it('accepts exact, rounded and ms->seconds conversions; flags invented numbers', () => {
    const s = sampleSummary();
    expect(findUngroundedNumbers(['48,200 impressions', 'Position 14.2', 'CTR 1.6%'], s)).toEqual([]);
    expect(findUngroundedNumbers(['Sessions: 5,401'], s)).toEqual([]); // within 1%
    expect(findUngroundedNumbers(['Sessions: 77,777'], s)).toEqual([77777]);
  });
});

describe('buildFallbackInsights (deterministic)', () => {
  it('always returns exactly 5 valid, data-backed actions without guarantees', () => {
    const s = sampleSummary();
    const out = buildFallbackInsights(s);
    expect(out.action_items).toHaveLength(5);
    expect(out.action_items.map((a) => a.priority)).toEqual([1, 2, 3, 4, 5]);
    // The fallback passes the same validation the AI must pass (incl. grounding).
    expect(parseInsightOutput(out, { requireHinglish: true, source: s }).ok).toBe(true);
    expect(out.action_items[0]!.title).toMatch(/lost the most/);
    expect(out.summary).toMatch(/generated by rules/);
  });

  it('is deterministic (same input -> same output)', () => {
    expect(buildFallbackInsights(sampleSummary())).toEqual(buildFallbackInsights(sampleSummary()));
  });

  it('works with almost no data (only speed) and recommends connecting sources', () => {
    const s = sampleSummary({ search_console: null, analytics: null });
    const out = buildFallbackInsights(s);
    expect(out.action_items).toHaveLength(5);
    const titles = out.action_items.map((a) => a.title).join(' | ');
    expect(titles).toMatch(/Connect Google Search Console/);
    expect(titles).toMatch(/Connect Google Analytics 4/);
    expect(parseInsightOutput(out, { source: s }).ok).toBe(true);
  });
});

describe('generateInsights (retry once, then fallback)', () => {
  const fakeEnv = (responses: (unknown | Error)[]) => {
    const calls: unknown[] = [];
    return {
      calls,
      env: {
        AI_MODEL: '@cf/test/model',
        AI_GATEWAY_ID: '',
        AI: {
          run: async (_m: string, input: unknown) => {
            calls.push(input);
            const next = responses.shift();
            if (next instanceof Error) throw next;
            return { response: next };
          },
        } as unknown as Ai,
      },
    };
  };

  it('returns AI output on the first valid answer', async () => {
    const t = fakeEnv([validAiOutput]);
    const r = await generateInsights(t.env, sampleSummary());
    expect(r.source).toBe('ai');
    expect(r.data.action_items).toHaveLength(5);
    expect(t.calls).toHaveLength(1);
  });

  it('retries once with the validation error, then succeeds', async () => {
    const t = fakeEnv(['garbage', JSON.stringify(validAiOutput)]);
    const r = await generateInsights(t.env, sampleSummary());
    expect(r.source).toBe('ai');
    expect(t.calls).toHaveLength(2);
    const retryMessages = (t.calls[1] as { messages: { content: string }[] }).messages;
    expect(retryMessages.at(-1)?.content).toMatch(/invalid/);
  });

  it('falls back to rules after two invalid answers (never throws)', async () => {
    const t = fakeEnv(['bad', 'still bad']);
    const r = await generateInsights(t.env, sampleSummary());
    expect(r.source).toBe('fallback');
    expect(r.model).toBe('rule-based-fallback');
    expect(r.fallbackReason).toMatch(/invalid output twice/);
    expect(r.data.action_items).toHaveLength(5);
  });

  it('falls back when the AI service errors', async () => {
    const t = fakeEnv([new Error('Workers AI: capacity exceeded')]);
    const r = await generateInsights(t.env, sampleSummary());
    expect(r.source).toBe('fallback');
    expect(r.fallbackReason).toMatch(/capacity exceeded/);
  });
});
